def generate_scrap_commentary(
    current_price,
    fair_actual_price,
    fair_value,
    spread_z,
    forecast_next_month,
    price_trend,
    trend_change_pct,
    trend_start_date,
    trend_end_date
):

    # ======================================================
    # 1. РАСЧЁТЫ
    # ======================================================

    fair_value_diff_pct = (
        (fair_actual_price - fair_value)
        / fair_value
        * 100
    )

    forecast_change_pct = (
        (forecast_next_month - current_price)
        / current_price
        * 100
    )


    # ======================================================
    # 2. СОСТОЯНИЕ РЫНКА ПО Z-SCORE
    # Используется внутри модели, пользователю число не показываем
    # ======================================================

    if spread_z >= 2:
        market_state = "strong_overheated"
        z_text = "цена существенно выше обычного рыночного диапазона"

    elif spread_z >= 1:
        market_state = "moderate_overheated"
        z_text = "цена находится выше обычного рыночного диапазона"

    elif spread_z <= -2:
        market_state = "strong_undervalued"
        z_text = "цена существенно ниже обычного рыночного диапазона"

    elif spread_z <= -1:
        market_state = "moderate_undervalued"
        z_text = "цена находится ниже обычного рыночного диапазона"

    else:
        market_state = "normal"
        z_text = "цена находится в пределах обычного рыночного диапазона"


    # ======================================================
    # 3. ОЦЕНКА ЦЕНЫ ОТНОСИТЕЛЬНО FAIR VALUE
    # ======================================================

    if fair_value_diff_pct <= -5:
        valuation_state = "discount"

    elif fair_value_diff_pct >= 5:
        valuation_state = "premium"

    else:
        valuation_state = "fair"


    # ======================================================
    # 4. ПРОГНОЗ НА СЛЕДУЮЩИЙ МЕСЯЦ
    # ======================================================

    if forecast_change_pct >= 2:

        forecast_state = "up"

        forecast_text = (
            f"Прогноз на следующий месяц предполагает "
            f"рост до {forecast_next_month:,.0f} ₽/т "
            f"({forecast_change_pct:+.1f}%)"
        )

    elif forecast_change_pct <= -2:

        forecast_state = "down"

        forecast_text = (
            f"Прогноз на следующий месяц предполагает "
            f"снижение до {forecast_next_month:,.0f} ₽/т "
            f"({forecast_change_pct:+.1f}%)"
        )

    else:

        forecast_state = "neutral"

        forecast_text = (
            f"Прогноз на следующий месяц предполагает "
            f"сохранение цены вблизи текущего уровня — "
            f"{forecast_next_month:,.0f} ₽/т "
            f"({forecast_change_pct:+.1f}%)"
        )


    # ======================================================
    # 5. РЕШЕНИЕ СИСТЕМЫ
    # ======================================================

    # ------------------------------------------------------
    # ПАДАЮЩИЙ РЫНОК
    # ------------------------------------------------------

    if price_trend == "down":

        if forecast_state == "down":

            purchase_signal = "avoid"

            purchase_title = (
                "🔴 НИСХОДЯЩИЙ ТРЕНД СОХРАНЯЕТСЯ"
            )

            recommendation = (
                "Фактические котировки продолжают снижаться, "
                "и прогноз указывает на сохранение давления на цену. "
                "При отсутствии срочной потребности закупку "
                "целесообразно отложить."
            )


        elif forecast_state == "up":

            purchase_signal = "buy"

            purchase_title = (
                "🟢 ВОЗМОЖНО ФОРМИРОВАНИЕ РАЗВОРОТА"
            )

            recommendation = (
                "Несмотря на сохраняющееся снижение фактических "
                "котировок, прогноз указывает на возможное "
                "восстановление цены. Можно рассмотреть частичное "
                "покрытие потребности, не дожидаясь подтверждённого роста."
            )


        else:

            purchase_signal = "watch"

            purchase_title = (
                "🟡 СНИЖЕНИЕ ПРОДОЛЖАЕТСЯ, "
                "ПРОГНОЗ УКАЗЫВАЕТ НА ВОЗМОЖНОЕ ЗАМЕДЛЕНИЕ"
            )

            recommendation = (
                "Фактические котировки продолжают снижаться. "
                "Прогноз предполагает сохранение цены вблизи "
                "текущего уровня, однако фактического подтверждения "
                "стабилизации рынка пока нет. "
                "При отсутствии срочной потребности закупку "
                "целесообразно отложить до появления признаков "
                "стабилизации котировок."
            )


    # ------------------------------------------------------
    # РАСТУЩИЙ РЫНОК
    # ------------------------------------------------------

    elif price_trend == "up":

        if forecast_state == "up":

            if market_state in [
                "strong_overheated",
                "moderate_overheated"
            ]:

                purchase_signal = "watch"

                purchase_title = (
                    "🟠 РОСТ ПРОДОЛЖАЕТСЯ, "
                    "НО ЦЕНА УЖЕ ПОВЫШЕНА"
                )

                recommendation = (
                    "Котировки продолжают расти, однако текущий "
                    "уровень цены уже находится выше обычного "
                    "рыночного диапазона. Опережающее увеличение "
                    "закупок на текущем уровне требует осторожности."
                )

            else:

                purchase_signal = "buy"

                purchase_title = (
                    "🟢 ВОСХОДЯЩИЙ ТРЕНД СОХРАНЯЕТСЯ"
                )

                recommendation = (
                    "Фактические котировки продолжают расти, "
                    "и прогноз указывает на сохранение положительной "
                    "динамики. При наличии плановой потребности "
                    "можно рассмотреть частичное опережающее покрытие."
                )


        elif forecast_state == "down":

            purchase_signal = "watch"

            purchase_title = (
                "🟡 РОСТ МОЖЕТ БЫТЬ БЛИЗОК К ИСЧЕРПАНИЮ"
            )

            recommendation = (
                "Несмотря на сохраняющийся рост фактических "
                "котировок, прогноз указывает на возможное снижение "
                "в следующем месяце. Увеличивать закупки на текущем "
                "уровне целесообразно с осторожностью."
            )


        else:

            purchase_signal = "watch"

            purchase_title = (
                "🟡 РОСТ СОХРАНЯЕТСЯ, "
                "ПРОГНОЗ НЕ ПОДТВЕРЖДАЕТ УСКОРЕНИЯ"
            )

            recommendation = (
                "Фактические котировки продолжают расти, "
                "однако прогноз предполагает сохранение цены "
                "вблизи текущего уровня. Выраженного сигнала "
                "для опережающего увеличения закупок нет."
            )


    # ------------------------------------------------------
    # БОКОВОЙ РЫНОК
    # ------------------------------------------------------

    else:

        if (
            valuation_state == "discount"
            and forecast_state == "up"
        ):

            purchase_signal = "buy"

            purchase_title = (
                "🟢 ПОЯВЛЯЕТСЯ СИГНАЛ К РОСТУ"
            )

            recommendation = (
                "Текущий уровень цены находится ниже расчётного "
                "равновесного значения, а прогноз указывает на "
                "возможный рост. Можно рассмотреть частичное "
                "восполнение запасов."
            )


        elif (
            market_state in [
                "strong_overheated",
                "moderate_overheated"
            ]
            and forecast_state != "up"
        ):

            purchase_signal = "avoid"

            purchase_title = (
                "🔴 ЦЕНА НАХОДИТСЯ В ПОВЫШЕННОЙ ЗОНЕ"
            )

            recommendation = (
                "Текущий уровень цены находится выше обычного "
                "рыночного диапазона, при этом прогноз не указывает "
                "на дальнейшее усиление роста. При отсутствии "
                "срочной потребности закупку целесообразно отложить."
            )


        else:

            purchase_signal = "watch"

            purchase_title = (
                "🟡 ВЫРАЖЕННОГО ЦЕНОВОГО СИГНАЛА НЕТ"
            )

            recommendation = (
                "Выраженного направленного движения котировок "
                "и сильного ценового сигнала пока нет. "
                "Целесообразно сохранить текущую закупочную стратегию."
            )


    # ======================================================
    # 6. АНАЛИТИЧЕСКИЙ КОММЕНТАРИЙ
    # ======================================================

    months_ru = {
        1: "января",
        2: "февраля",
        3: "марта",
        4: "апреля",
        5: "мая",
        6: "июня",
        7: "июля",
        8: "августа",
        9: "сентября",
        10: "октября",
        11: "ноября",
        12: "декабря"
    }

    start_date_text = (
        f"{trend_start_date.day} "
        f"{months_ru[trend_start_date.month]}"
    )

    end_date_text = (
        f"{trend_end_date.day} "
        f"{months_ru[trend_end_date.month]}"
    )


    # ------------------------------------------------------
    # ФАКТИЧЕСКИЙ ТРЕНД
    # ------------------------------------------------------

    if price_trend == "down":

        trend_comment = (
            f"С {start_date_text} по {end_date_text} "
            f"цена лома снизилась на "
            f"{abs(trend_change_pct):.1f}%"
        )

    elif price_trend == "up":

        trend_comment = (
            f"С {start_date_text} по {end_date_text} "
            f"цена лома выросла на "
            f"{abs(trend_change_pct):.1f}%"
        )

    else:

        trend_comment = (
            f"С {start_date_text} по {end_date_text} "
            f"выраженного направленного движения "
            f"котировок не наблюдалось"
        )


    # ------------------------------------------------------
    # ИНТЕРПРЕТАЦИЯ ТЕКУЩЕГО УРОВНЯ ЦЕНЫ
    # ------------------------------------------------------

    if valuation_state == "discount":

        valuation_text = (
            "Текущий уровень цены находится ниже "
            "расчётного равновесного значения, что формирует "
            "ценовой дисконт"
        )

    elif valuation_state == "premium":

        valuation_text = (
            "Текущий уровень цены находится выше "
            "расчётного равновесного значения, поэтому "
            "текущие котировки выглядят повышенными"
        )

    else:

        valuation_text = (
            "Текущий уровень цены близок к расчётному "
            "равновесному значению — выраженного ценового "
            "дисконта или переоценённости нет"
        )


    # ------------------------------------------------------
    # ИТОГОВЫЙ КОММЕНТАРИЙ
    # ------------------------------------------------------

    comment = (
        f"{trend_comment}. "
        f"{valuation_text}. "
        f"{forecast_text}."
    )


    # ======================================================
    # RETURN
    # ======================================================

    return {

        "purchase_signal": purchase_signal,

        "purchase_title": purchase_title,

        "market_state": market_state,

        "market_state_text": z_text,

        "price_trend": price_trend,

        "comment": comment,

        "forecast_text": forecast_text,

        "recommendation": recommendation,

        "fair_value_diff_pct": round(
            float(fair_value_diff_pct), 1
        ),

        "forecast_change_pct": round(
            float(forecast_change_pct), 1
        ),

        "trend_change_pct": round(
            float(trend_change_pct), 1
        ),

        "spread_z": round(
            float(spread_z), 2
        )
    }